// 泡泡法典：每個從外面進來的訊號，一進門就被包進一個泡泡。先寫表，引擎只照表走。
//
// 泡泡上寫：從哪裡來、是誰帶進來的（父泡泡）、內容的指紋、經過哪些檢查、各蓋了什麼章。
// 每次動泡泡，就把「上一個鏈值＋這次做的事」重新算一次指紋，串成一條鏈；事後任何一個字被改，都對得出來。

export const 狀態們 = ["門外", "已包", "檢查中", "已判定", "剪斷"];
export const 事件們 = ["包", "蓋章", "判定", "剪斷"];

// 轉移表：(現在狀態, 事件) → 下一個狀態；表上沒有的組合一律拒絕。
export const 轉移表 = {
  "門外|包": "已包",
  "已包|蓋章": "檢查中",
  "檢查中|蓋章": "檢查中",
  "檢查中|判定": "已判定",
  "已包|剪斷": "剪斷",
  "檢查中|剪斷": "剪斷",
  "已判定|剪斷": "剪斷",
};

// 規矩（引擎守衛會一條一條執行，檢查器會窮舉確認）
export const 規矩 = [
  "沒有包泡泡的訊號，什麼都不能做（門外只能被包）",
  "沒蓋過任何章，不能判定",
  "判定之後不能再蓋章、不能改判（只能被剪斷）",
  "剪斷之後什麼都不能做",
  "子泡泡掛在父泡泡的繩上；父泡泡被剪斷，整條繩上的子孫全部剪斷",
  "章只能往上加，不能刪、不能改；每加一個，鏈值就重算一次",
];

// 檢查器：窮舉所有 (狀態, 事件)，找出違反規矩的列
export function 檢查泡泡法典(表 = 轉移表) {
  const 問題 = [];
  for (const 狀 of 狀態們) for (const 事 of 事件們) {
    const 到 = 表[`${狀}|${事}`];
    if (到 === undefined) continue;
    if (!狀態們.includes(到)) 問題.push(`${狀}×${事} 走到不存在的狀態「${到}」`);
    if (狀 === "門外" && 事 !== "包") 問題.push(`門外的訊號竟然可以「${事}」`);
    if (狀 === "剪斷") 問題.push(`剪斷之後竟然還能「${事}」`);
    if (狀 === "已判定" && (事 === "蓋章" || 事 === "判定")) 問題.push(`判定之後竟然還能「${事}」`);
    if (狀 === "已包" && 事 === "判定") 問題.push("沒蓋章就能判定");
    if (事 === "剪斷" && 到 !== "剪斷") 問題.push(`${狀}×剪斷 沒有走到剪斷`);
  }
  for (const 狀 of ["已包", "檢查中", "已判定"])
    if (表[`${狀}|剪斷`] !== "剪斷") 問題.push(`${狀} 的泡泡剪不斷`);
  return 問題;
}
