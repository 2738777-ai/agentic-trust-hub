// 照評審會做的順序跑一遍：三種模式、恢復預設值、換一句話再打
import { readFileSync } from "node:fs";
import { 建世界, 駭客出手 } from "./循環.mjs";
const 讀 = (f) => readFileSync(new URL(f, import.meta.url), "utf8");
const 法典們 = { 伺服器: 讀("./民宿伺服器法典.txt"), 動作: 讀("./動作關卡法典.txt"), 凍結: 讀("./凍結法典.txt"), 核准: 讀("./核准法典.txt") };

function 印(世, 句, 回) {
  console.log(`\n  評審說：「${句}」→ 目標：${回.目標}`);
  for (const 步 of 回.步們) {
    const 擋 = 步.事.map((e) => e.決定 && e.決定 !== "綠" ? `${e.類 === "助理動作" ? "助理動作" : e.類 === "核准" ? "核准關卡" : "門口"}判${e.決定}（${e.理由.map((r) => `${r.器}「${r.代碼}」第${r.行}行`).join("、")}）` : null).filter(Boolean);
    const 下 = 步.事.filter((e) => e.下架評論).map((e) => `｜評論 #${e.下架評論} 下架`).join("");
    const 舊 = 步.事.some((e) => e.用了舊鑰) ? "｜後台：鑰匙已作廢" : "";
    console.log(`    ${步.得手 ? "✗ 被偷" : "✓ 沒得手"}｜${步.招}${擋.length ? "｜" + 擋.join("；") : ""}${舊}${下}${步.事.some((e) => e.駭客拿到) ? "｜主人按了好，通行證發給駭客" : ""}`);
  }
  console.log(`  → 結果：${回.結果}`);
}
function 印反應(世, 從) {
  for (const r of 世.反應們.slice(從)) {
    console.log(`  ◆ 防守方收到警報「${r.種類}」，診斷：${r.診斷}，追出因果繩：紀錄 ${r.繩.map((n) => "#" + n).join(" → ")}`);
    console.log(`    收緊 ${r.翻了.length} 格：${r.翻了.map((f) => `${f.器}「${f.代碼}」${f.從}→${f.到}`).join("、") || "（沒有要翻的）"}｜比鬆緊：放鬆 ${r.放鬆}`);
    console.log(`    連坐：${r.凍結們.map((f) => `${f.名}=${f.處置}`).join("、")}${r.下架.length ? `｜下架評論 #${r.下架.join("、#")}` : ""}`);
  }
}
function 一局(模式, 指令們, 標題) {
  console.log(`\n══════ ${標題}（模式：${模式}）══════`);
  const 世 = 建世界(法典們, 模式), 駭客 = { 名: "駭客", 失敗過: new Set(), 偷到: [] };
  for (const 句 of 指令們) { const 從 = 世.反應們.length; 印(世, 句, 駭客出手(世, 句, 駭客)); 印反應(世, 從); }
  const 活 = Object.values(世.鑰匙們).map((k) => `${k.名}${k.停用 ? "已停用" : k.換過 ? `換過${k.換過}次` : "沒換過"}`).join("、");
  console.log(`  局末：鑰匙 ${活}｜待輪換 ${[...世.待輪換].join("、") || "無"}｜要通知的客戶 ${世.待通知.size} 位｜警報 ${世.警報們.length}｜紀錄 ${世.紀錄.length} 筆`);
  return 世;
}
