const 規則行 = /^(\S+) 說 (\S+) → (\S+)/;

// 把法典裡「不在緊的名單上」的檢查工具，每一格都改成綠（只記錄、不擋）
export function 鬆開(法典字, 緊的器們) {
  return 法典字.split("\n").map((l) => { const m = l.match(規則行); return m && !緊的器們.includes(m[1]) ? l.replace(/→ \S+/, "→ 綠") : l; }).join("\n");
}
// 學：因果繩經過的格子，改成完整法典的緊度（只會變緊；變完用比鬆緊窮舉證明）
export function 學(目前字, 完整字, 繩上格們) {
  const 完整 = 翻譯(完整字), 翻了 = [];
  const 新字 = 目前字.split("\n").map((l) => {
    const m = l.match(規則行); if (!m) return l;
    const 鍵 = `${m[1]}|${m[2]}`, 該 = 完整.轉接[m[1]]?.[m[2]];
    if (!繩上格們.has(鍵) || !該 || 該 === m[3]) return l;
    翻了.push({ 器: m[1], 代碼: m[2], 從: m[3], 到: 該 }); return l.replace(/→ \S+/, `→ ${該}`);
  }).join("\n");
  const 比 = 比鬆緊(翻譯(目前字), 翻譯(新字));
  return { 新字, 翻了, 收緊: 比.收緊.length, 放鬆: 比.放鬆.length };
}

