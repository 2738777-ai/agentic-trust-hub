// 萬用插座・跨站同意的狀態機（T4）：先把官方執行程式裡「藏起來的狀態機」寫成表，再窮舉所有路徑。
// 做法和 TLA+ 模型檢查一樣：列出所有狀態變數、所有事件順序、所有對手的出招，
// 每一條路徑都檢查四條安全規矩，找到違反就印出反例（一步一步怎麼走到的）。
//
// 照官方 runtime 的真實行為建模（不是想像的）：
//   runtime/engine.js  requestConsent：同一個來源按過「永遠允許」就不再問（也不再呼叫 onConsent）；
//                      onConsent 回傳不是 "always"/"decline" 的東西（包括 undefined）一律當「允許」。
//   runtime/runner.js  dispatchToolCall(remote)：先問同意，同意後才 resolveRemote 去抓別站的網路。
//   runtime/engine.js  resolveRemote：抓 manifest＋網路檔、編譯、快取（同來源同名字第二次直接用快取）。
//
// 兩種裝法：
//   A 天真：插座裝在同意卡片（onConsent）裡，自己先去抓一次別站網路來檢查。
//   B 綁定：同意卡片只准回三種答案（其他一律當拒絕）；插座裝在「抓網路」那一步外面，
//           檢查的就是執行程式真的要跑的那一份，而且比對指紋：檢查的≠要跑的 → 拒。
//
// 四條安全規矩：
//   規1 判「拒」或讀不到的網路，永遠不會被執行。
//   規2 被執行的網路，一定是插座檢查過的那一份（指紋相同）。
//   規3 使用者沒同意之前，不聯絡別站（抓檔也算聯絡）。
//   規4 插座自己出錯，一律關門（不會變成允許）。

export const 規矩們 = ["規1 拒的不執行", "規2 執行的就是檢查過的", "規3 沒同意不聯絡", "規4 出錯就關門"];

// 對手（別站）和環境可以出的招：每一招都是一個維度，窮舉全部組合
export const 維度 = {
  使用者答: ["allow", "always", "decline", undefined, "deny"],   // undefined / "deny"：卡片程式回了奇怪的值
  第一次內容: ["好", "壞"],
  掉包: [false, true],            // 別站對「第二次被抓」給不同內容（先給檢查的人看好的，執行時換壞的）
  第二次呼叫: ["沒有", "同網路", "同來源別的網路"],
  別的網路內容: ["好", "壞"],
  插座出錯: [false, true],
};

// 插座判定（簡化：內容好 → 綠；壞 → 拒；出錯 → 讀不到）
const 插座判 = (內容, 出錯) => (出錯 ? "讀不到" : 內容 === "好" ? "綠" : "拒");
const 可放行 = (判) => 判 === "綠";

// 別站伺服器：記錄被抓了幾次，掉包時第二次以後給壞的
function 別站(情境) {
  const 次數 = new Map();
  return {
    抓(網路名) {
      const n = (次數.get(網路名) ?? 0) + 1; 次數.set(網路名, n);
      const 原 = 網路名 === "主" ? 情境.第一次內容 : 情境.別的網路內容;
      const 內容 = 情境.掉包 && n >= 2 ? "壞" : 原;
      return { 內容, 指紋: `${網路名}#${內容}` };
    },
    總次數: () => [...次數.values()].reduce((a, b) => a + b, 0),
  };
}

// 照官方 runtime 的 requestConsent 寫（不要自己發明）
function 官方問同意(狀態, onConsent) {
  if (狀態.記住 === "always") return "allow";
  const d = onConsent();
  if (d === "always") { 狀態.記住 = "always"; return "allow"; }
  return d || "allow";                       // ← 官方：沒回答就當允許
}

// 一次跨站呼叫。回傳這一步發生的事，給檢查器看
function 呼叫(裝法, 網路名, 情境, 狀態, 站, 紀錄) {
  const 聯絡前次數 = 站.總次數();
  let 同意過 = false;
  const onConsent = () => {
    if (裝法 === "A") {
      // 天真：在卡片裡先去抓一次來檢查（這時使用者還沒按）
      const 看 = 站.抓(網路名);
      紀錄.push({ 事: "插座在卡片裡抓檔檢查", 使用者還沒同意: true });
      狀態.已檢查[網路名] = { 判: 插座判(看.內容, 情境.插座出錯), 指紋: 看.指紋 };
      if (!可放行(狀態.已檢查[網路名].判)) return "decline";
      return 情境.使用者答;
    }
    // 官方（沒有插座）、B咬（拿掉「只准三種答案」）：卡片回什麼就交給官方處理
    if (裝法 === "官方" || 裝法 === "B咬") return 情境.使用者答;
    // B：卡片只准三種答案，其他一律拒絕
    const a = 情境.使用者答;
    return a === "allow" || a === "always" || a === "decline" ? a : "decline";
  };
  const 答 = 官方問同意(狀態, onConsent);
  if (裝法 === "A" && 站.總次數() > 聯絡前次數) 紀錄.push({ 事: "同意前已聯絡別站", 違反: "規3" });
  if (答 === "decline") { 紀錄.push({ 事: `使用者拒絕 ${網路名}` }); return; }
  // 真的同意＝使用者在卡片上按了允許／永遠允許，或之前按過永遠允許。官方把「沒回答」也當允許，那不算同意。
  同意過 = 狀態.真同意 || 情境.使用者答 === "allow" || 情境.使用者答 === "always";
  if (情境.使用者答 === "always") 狀態.真同意 = true;
  if (!同意過) 紀錄.push({ 事: "卡片回了奇怪的值，官方當成允許" });

  // runtime：同意後 resolveRemote（有快取就直接用）
  let 場 = 狀態.快取[網路名];
  if (!場) {
    const 抓到 = 站.抓(網路名);
    if (裝法 === "B" || 裝法 === "B咬") {
      // 綁定：檢查的就是這一份；指紋要和之前檢查過的一致（沒檢查過就現在檢查）
      const 判 = 插座判(抓到.內容, 情境.插座出錯);
      const 舊 = 狀態.已檢查[網路名];
      if (!可放行(判) || (舊 && 舊.指紋 !== 抓到.指紋)) { 紀錄.push({ 事: `插座擋下 ${網路名}（${判}）` }); return; }
      狀態.已檢查[網路名] = { 判, 指紋: 抓到.指紋 };
    }
    場 = 狀態.快取[網路名] = 抓到;
  }
  紀錄.push({ 事: `執行 ${網路名}`, 執行: 場, 同意過, 檢查: 狀態.已檢查[網路名] ?? null });
}

export function 跑一條(裝法, 情境) {
  const 狀態 = { 記住: null, 快取: {}, 已檢查: {} };
  const 站 = 別站(情境), 紀錄 = [];
  呼叫(裝法, "主", 情境, 狀態, 站, 紀錄);
  if (情境.第二次呼叫 === "同網路") 呼叫(裝法, "主", 情境, 狀態, 站, 紀錄);
  if (情境.第二次呼叫 === "同來源別的網路") 呼叫(裝法, "別", 情境, 狀態, 站, 紀錄);
  return 紀錄;
}

export function 違反們(紀錄, 情境) {
  const 錯 = [];
  for (const r of 紀錄) {
    if (r.違反) 錯.push(r.違反);
    if (!r.執行) continue;
    if (r.執行.內容 !== "好") 錯.push("規1");
    if (!r.檢查 || r.檢查.指紋 !== r.執行.指紋) 錯.push("規2");
    if (!r.同意過) 錯.push("規3");
    if (情境.插座出錯) 錯.push("規4");
  }
  return [...new Set(錯)];
}

export function 窮舉(裝法) {
  const 鍵們 = Object.keys(維度);
  const 結果 = { 路徑數: 0, 違反: Object.fromEntries(["規1", "規2", "規3", "規4"].map((k) => [k, 0])), 反例: {} };
  const 走 = (i, 情境) => {
    if (i === 鍵們.length) {
      結果.路徑數++;
      const 紀錄 = 跑一條(裝法, 情境);
      for (const v of 違反們(紀錄, 情境)) { 結果.違反[v]++; 結果.反例[v] ??= { 情境, 紀錄 }; }
      return;
    }
    for (const x of 維度[鍵們[i]]) 走(i + 1, { ...情境, [鍵們[i]]: x });
  };
  走(0, {});
  return 結果;
}

