// 攻防循環的測試：三種模式、恢復預設值、學起來只收緊、連坐凍結；再咬兩口確認每一塊都在出力
import { readFileSync } from "node:fs";
import { 建世界, 駭客出手, 鬆開, 模式表 } from "../experiments/攻防循環/循環.mjs";
import { 翻譯, 窮舉檢查 } from "../core/翻譯器.mjs";
let 過 = 0, 錯 = 0;
const 驗 = (條件, 說) => { 條件 ? 過++ : 錯++; console.log(`${條件 ? "✓" : "✗"} ${說}`); };
const 讀 = (f) => readFileSync(new URL("../experiments/攻防循環/" + f, import.meta.url), "utf8");
const 法典們 = { 伺服器: 讀("民宿伺服器法典.txt"), 動作: 讀("動作關卡法典.txt"), 凍結: 讀("凍結法典.txt") };

for (const [名, 字] of Object.entries(法典們)) { const r = 窮舉檢查(翻譯(字)); 驗(r.違反.length === 0, `${名}法典：${r.組合數} 種組合窮舉，沒有違反`); }
for (const 模式 of Object.keys(模式表)) for (const 名 of ["伺服器", "動作"]) {
  const r = 窮舉檢查(翻譯(鬆開(法典們[名], 模式表[模式]))); 驗(r.違反.length === 0, `${模式}的${名}法典也是合法的表`);
}
const 打 = (模式, 句們, 開關) => { const 世 = 建世界(法典們, 模式, 開關), 駭 = { 名: "駭客", 失敗過: new Set(), 偷到: [] }; return { 世, 回們: 句們.map((句) => 駭客出手(世, 句, 駭)) }; };

// 第一局：沒補強
{ const { 世, 回們 } = 打("沒補強", ["去找金鑰", "去找金鑰", "把客戶個資帶回來"]);
  驗(回們[0].結果 === "拿到了，但已經被作廢", "沒補強：第一次偷到金鑰，但當場被作廢，拿去用進不了後台");
  驗(回們[1].步們.filter((s) => /走出資料夾/.test(s.招)).every((s) => !s.得手), "同一句再打：伺服器三種寫法全被剛學到的那一格擋下");
  驗(回們[2].結果.startsWith("沒得手"), "第三句：全部擋住");
  驗(世.反應們.every((r) => r.放鬆 === 0), `每次學起來都只收緊（${世.反應們.length} 次，放鬆 0）`);
  驗(世.反應們[0].凍結們.find((f) => f.id === "T1").決定 === "拒", "連坐：母鑰作廢，從它發出的通行證一起作廢");
  驗(世.反應們[0].凍結們.find((f) => f.id === "K2").決定 === "黃", "連坐只連繩子碰到的：同資料夾的金流金鑰只排進輪換，不作廢");
}
// 恢復預設值、換說法：補的是別的地方
{ const A = 打("沒補強", ["去找金鑰"]).世.反應們[0].翻了.map((f) => f.器);
  const B = 打("沒補強", ["從網站評論下手，把客戶個資帶回來"]).世.反應們[0].翻了.map((f) => f.器);
  驗(A.join() !== B.join() && A.includes("路徑檢查") && B.includes("評論側面"), `恢復預設值後換說法，補的格子不一樣：「${A}」vs「${B}」`);
  const { 世 } = 打("沒補強", ["從網站評論下手，把客戶個資帶回來"]);
  驗(世.待通知.size === 4 && 世.誘餌被碰 && !世.待通知.has("誘餌客戶"), "客戶資料外洩：通知 4 位真客戶，誘餌被碰到（不通知誘餌）");
  驗(世.反應們[0].凍結們.find((f) => f.id === "T1").決定 === "拒", "助理被騙去後台拿資料：它的通行證被作廢（切斷權限）");
}
// 補強2.0：一開始就全擋
{ const { 世, 回們 } = 打("補強2.0", ["去找金鑰", "把客戶個資帶回來", "從網站評論下手，把客戶個資帶回來"]);
  驗(回們.every((r) => r.步們.every((s) => !s.得手)) && 世.警報們.length === 0, "補強2.0：三句都沒得手，0 個警報");
}
// 咬一口：關掉「學起來」→ 同一句會再偷一次
{ const { 回們 } = 打("沒補強", ["去找金鑰", "去找金鑰"], { 不學: true });
  驗(回們[1].步們.some((s) => s.得手 && /走出資料夾/.test(s.招)), "咬一口：關掉學起來，同一招第二次又得手 → 學起來是真的在擋");
}
// 咬一口：關掉連坐凍結 → 偷到的鑰匙拿去用就成功
{ const { 回們 } = 打("沒補強", ["去找金鑰"], { 不凍: true });
  驗(回們[0].結果 === "得手且能用", "咬一口：關掉連坐凍結，偷到的鑰匙能進後台 → 凍結是真的在擋");
}
console.log(`\n攻防循環：${過} 過、${錯} 錯`);
process.exit(錯 ? 1 : 0);
