// 跨站同意狀態機（T4）：窮舉證明裝法 B 四條規矩 0 違反；天真裝法、官方本身、拿掉一條規矩都抓得到違反（咬人測試）。
import { 窮舉 } from "../experiments/跨站同意/狀態機.mjs";
let 過 = 0, 錯 = 0;
const 驗 = (c, 名) => { c ? 過++ : 錯++; console.log((c ? "通過 " : "失敗 ") + 名); };
const B = 窮舉("B"), A = 窮舉("A"), 官 = 窮舉("官方"), 咬 = 窮舉("B咬");
驗(B.路徑數 === 240 && Object.values(B.違反).every((n) => n === 0), `裝法 B：${B.路徑數} 條路徑，四條規矩 0 違反`);
驗(A.違反.規3 > 0 && A.違反.規1 > 0 && A.違反.規2 > 0, "天真裝法 A 抓得到：同意前就聯絡、先查後掉包、永遠允許後別的網路沒檢查");
驗(官.違反.規1 > 0 && 官.違反.規3 > 0, "官方本身（沒插座）：壞網路會跑；卡片回奇怪的值會被當允許");
驗(咬.違反.規3 > 0, "咬人：B 拿掉「卡片只准三種答案」，規3 就破");
console.log(`\n跨站同意：${過} 過、${錯} 錯`);
process.exitCode = 錯 ? 1 : 0;
